#!/usr/bin/env python3
"""gen_unicode.py — regenerate runtime/src/unicode_tab.h.

A development-time tool only: the build never runs it. It reads the Unicode
Character Database bundled with Python's `unicodedata` module and writes the
compact range tables libvoila uses for `upper`, `lower`, `title`, `is_alpha`
and `is_upper`.

Case mapping is Unicode's SIMPLE (1:1) mapping, UnicodeData.txt fields
12-14, as Go's unicode.ToUpper uses. Python exposes only the FULL mapping
(SpecialCasing applied), so the simple one is recovered from it:
  - a full mapping of ONE character is the simple mapping;
  - a full uppercase that expands (ᾳ -> ΑΙ) has a one-character titlecase
    that IS the simple uppercase (ᾳ -> ᾼ) wherever a simple mapping exists;
  - U+0130 İ is the one character whose full LOWERCASE expands; its simple
    lowercase is plain i;
  - everything else that expands (ß -> SS, ŉ -> ʼN) has no simple mapping.
This derivation was checked against Perl's Unicode::UCD simple mappings for
every code point both databases assign.

    python3 tools/gen_unicode.py > runtime/src/unicode_tab.h

Every table is a sorted array of {lo, hi, stride[, delta]} rows. A code point
c is IN a row when lo <= c <= hi and (c - lo) % stride == 0. The stride lets a
single row cover the alternating Upper/lower pairs that fill Latin Extended-A,
Latin Extended Additional, Cyrillic, Greek and others (Ā ā Ă ă … is one row
with stride 2 instead of dozens of singletons).
"""
import sys
import unicodedata as ud

MAX = 0x110000


def one(m, c):
    """ord(m) when m is a single character, else c (no 1:1 mapping)."""
    return ord(m) if len(m) == 1 else c


def simple_upper(c):
    ch = chr(c)
    if len(ch.upper()) == 1:
        return ord(ch.upper())
    return one(ch.title(), c)


def simple_lower(c):
    if c == 0x130:
        return 0x69
    return one(chr(c).lower(), c)


def simple_title(c):
    return one(chr(c).title(), c)


def pack_map(pairs):
    """Pack a sorted list of (c, delta) into (lo, hi, stride, delta) rows."""
    rows = []
    for c, d in pairs:
        if rows:
            lo, hi, st, dd = rows[-1]
            if dd == d:
                # Extend the open row when c continues its arithmetic step.
                if lo == hi and c - hi in (1, 2):
                    rows[-1] = (lo, c, c - hi, dd)
                    continue
                if lo != hi and c - hi == st:
                    rows[-1] = (lo, c, st, dd)
                    continue
        rows.append((c, c, 1, d))
    return rows


def pack_set(cps):
    """Pack a sorted list of code points into (lo, hi, stride) rows."""
    return [(lo, hi, st) for lo, hi, st, _ in pack_map([(c, 0) for c in cps])]


def is_surrogate(c):
    return 0xD800 <= c <= 0xDFFF


upper, lower, title, letters, notupper, uppers = [], [], [], [], [], []
for c in range(MAX):
    if is_surrogate(c):
        continue
    ch = chr(c)
    if ud.category(ch).startswith("L"):
        letters.append(c)
    # is_upper follows Python's str.isupper exactly: a string is upper case
    # when it has no Lowercase-property or titlecase (Lt) character and at
    # least one Uppercase-property character. The Lowercase property is wider
    # than Ll (it has U+2170 ⅰ and U+24D0 ⓐ), so category alone is wrong.
    if ch.islower() or ud.category(ch) == "Lt":
        notupper.append(c)
    elif ch.isupper():
        uppers.append(c)
    u = simple_upper(c)
    if u != c:
        upper.append((c, u - c))
    lo = simple_lower(c)
    if lo != c:
        lower.append((c, lo - c))
    # Only where titlecase differs from uppercase (the DŽ/LJ/NJ/DZ digraphs):
    # every other code point titlecases exactly as it uppercases.
    t = simple_title(c)
    if t != u:
        title.append((c, t - c))


def emit_map(name, rows):
    print(f"static const VlCaseRow {name}[] = {{")
    for lo, hi, st, d in rows:
        print(f"  {{{{0x{lo:X}, 0x{hi:X}, {st}}}, {d}}},")
    print("};")
    print(f"#define {name.upper()}_N {len(rows)}\n")


def emit_set(name, rows):
    print(f"static const VlRangeRow {name}[] = {{")
    for lo, hi, st in rows:
        print(f"  {{0x{lo:X}, 0x{hi:X}, {st}}},")
    print("};")
    print(f"#define {name.upper()}_N {len(rows)}\n")


print("/* unicode_tab.h — GENERATED by tools/gen_unicode.py from the Unicode")
print(f" * Character Database {ud.unidata_version}. Do not edit by hand.")
print(" *")
print(" * Rows are sorted by `lo`; a code point c is covered by a row when")
print(" * lo <= c <= hi and (c - lo) % stride == 0. Case rows add `delta`. */")
print("#ifndef VOILA_UNICODE_TAB_H")
print("#define VOILA_UNICODE_TAB_H\n")
print("#include <stdint.h>\n")
print("typedef struct { uint32_t lo, hi; uint8_t stride; } VlRangeRow;")
print("/* The range is the FIRST member, so a VlCaseRow* converts to a valid")
print(" * VlRangeRow* and one search routine serves both tables. */")
print("typedef struct { VlRangeRow r; int32_t delta; } VlCaseRow;\n")
emit_map("vl_uc_upper", pack_map(upper))
emit_map("vl_uc_lower", pack_map(lower))
emit_map("vl_uc_title", pack_map(title))
emit_set("vl_uc_letter", pack_set(letters))
emit_set("vl_uc_notupper", pack_set(notupper))
emit_set("vl_uc_uppercase", pack_set(uppers))
print("#endif")
sys.stdout.flush()
